// npm run build:css — compile Tailwind for everything under /design into design/assets/css/app.css
// and vendor the Inter variable font into design/assets/fonts so mockups open offline.
//   Config: design/01-foundations/tailwind.config.js, else tools/tailwind/placeholder.config.js
//   Input:  design/01-foundations/input.css,          else tools/tailwind/input.css
import { createRequire } from 'node:module';
import { existsSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import postcss from 'postcss';
import { ROOT, DESIGN, ensureDir, rel } from './lib.mjs';

const require = createRequire(import.meta.url);
const tailwindcss = require('tailwindcss');
const loadConfig = require('tailwindcss/loadConfig');

const pick = (...paths) => paths.find((p) => existsSync(p));
const configPath = pick(join(DESIGN, '01-foundations/tailwind.config.js'), join(ROOT, 'tools/tailwind/placeholder.config.js'));
const inputPath = pick(join(DESIGN, '01-foundations/input.css'), join(ROOT, 'tools/tailwind/input.css'));
const outDir = join(DESIGN, 'assets');
const outCss = join(outDir, 'css/app.css');
const fontDir = join(outDir, 'fonts');

const t0 = Date.now();
try {
  const base = loadConfig(configPath);
  const config = {
    ...base,
    // HTML-specific wiring; the foundations config itself stays app-reusable.
    content: [join(DESIGN, '**/*.html'), join(ROOT, 'tools/flows/**/*.mjs')],
    darkMode: ['selector', '[data-theme="dark"]'],
    plugins: [...(base.plugins ?? []), require('./tailwind/lucide-plugin.js')],
  };

  // Inter variable font (normal + italic), url()s rewritten to ../fonts/
  const fontPkg = dirname(require.resolve('@fontsource-variable/inter/package.json'));
  ensureDir(fontDir);
  let fontCss = '';
  for (const sheet of ['index.css', 'wght-italic.css']) {
    const css = readFileSync(join(fontPkg, sheet), 'utf8');
    for (const [, file] of css.matchAll(/url\(\.\/files\/([^)]+)\)/g)) {
      copyFileSync(join(fontPkg, 'files', file), join(fontDir, file));
    }
    fontCss += css.replaceAll('url(./files/', 'url(../fonts/');
  }

  const result = await postcss([tailwindcss(config)]).process(readFileSync(inputPath, 'utf8'), { from: inputPath, to: outCss });
  for (const w of result.warnings()) console.warn('warn:', w.toString());
  ensureDir(dirname(outCss));
  writeFileSync(outCss, `/* Generated by npm run build:css — do not edit */\n${fontCss}\n${result.css}`);

  const kb = (Buffer.byteLength(result.css) / 1024).toFixed(1);
  console.log(`build:css OK in ${Date.now() - t0}ms`);
  console.log(`  config: ${rel(configPath)}`);
  console.log(`  input:  ${rel(inputPath)}`);
  console.log(`  output: ${rel(outCss)} (${kb} KB) + fonts in ${rel(fontDir)}`);
} catch (err) {
  console.error(`build:css FAILED: ${err.message}`);
  process.exit(1);
}
