# Usage: python3 tools/qa/coverage.py [Done|"Designed, pending QA"]  → design/05-qa/coverage.md
# Builds the coverage table from the screen files (frame counts, iOS/web/large-text variants) and the
# requirement citations in each spec. Status is passed in by the lead after QA.
import glob, os, re, sys
ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
SCR = os.path.join(ROOT, 'design', '03-screens')
status = sys.argv[1] if len(sys.argv) > 1 else 'Done'
NAMES = {}
for line in open(os.path.join(ROOT, 'design', '00-brief', 'requirements.md')):
    m = re.match(r'- \*\*SCR-(\d\d)\*\* S\d\d (.+)', line)
    if m:
        name = m.group(2).strip()
        note = re.search(r'\s*_(Changed by|Out of scope)([^_]*)_\s*$', name)
        if note:
            ds = ', '.join(dict.fromkeys(re.findall(r'D-\d\d', note.group(0))))
            name = name[:note.start()].strip() + (f' (changed by {ds}; see requirements.md)' if note.group(1) == 'Changed by' else '')
        NAMES[m.group(1)] = name
# Current titles where a build decision changed the brief's screen name (requirements.md keeps the original).
NAMES.update({
    '03': 'Sign up / sign in (Google, Apple, email; changed by D-13)',
    '12': 'Pre-permission explainers (contacts on Android 16 and lower, notifications) and permission-denied recovery (changed by D-18, D-32)',
    '13': 'Contacts import (system picker on Android 17+ and iOS; full list on Android 16 and lower; changed by D-18)',
    '15': "Google Sheets: choose a spreadsheet in Google's Picker, then its tabs (changed by D-17)",
})
# Screens kept for reference only (not part of the current design).
RETIRED = {'S18': 'Out of scope (D-32): retired, kept for reference'}
rows, total = [], 0
for html in sorted(glob.glob(os.path.join(SCR, 'S??-*.html'))):
    sid = os.path.basename(html)[:3]
    h = open(html).read()
    frames = re.findall(r'data-frame="([^"]+)"', h)
    total += len(frames)
    has = lambda pat: 'yes' if any(re.search(pat, f) for f in frames) else '—'
    ios, web = has(r'-ios'), has(r'-web')
    large = has(r'large-text')
    states = [k for k, pat in [('empty', r'empty|first-run|none|no-'), ('loading', r'loading|reading|connecting'), ('error', r'error|failed|denied|not-found|invalid|expired'), ('offline', r'offline')] if any(re.search(pat, f) for f in frames)]
    md = html[:-5] + '.md'
    spec = 'yes' if os.path.exists(md) else 'MISSING'
    rows.append(f'| {sid} | {NAMES.get(sid[1:], "")} | {len(frames)} | {", ".join(states) or "—"} | {ios} | {web} | {large} | {spec} | {RETIRED.get(sid, status)} |')
out = f"""# Coverage

Every screen ID with its frames and variants. Generated by `python3 tools/qa/coverage.py` from the screen
files; status set by the lead after QA (see review-report.md). Updated by the design update after build
planning (2026-10-11, `docs/design-update-report.md`).

**{len(rows)} screens, {total} frames, each in light and dark ({total * 2} screenshots).**

States column: which of empty / loading / error / offline are drawn (screens where a state cannot occur
explain why in their spec §4). iOS / Web / Large text: whether a variant frame exists (spec §8 explains
where none is needed).

| ID | Screen | Frames | States drawn | iOS | Web | Large text | Spec | Status |
| --- | --- | --- | --- | --- | --- | --- | --- | --- |
""" + '\n'.join(rows) + """

## Other deliverables

| Deliverable | Status |
| --- | --- |
| Foundations (tokens, Tailwind config, design system, components, motion, brand) | Done |
| Architecture (navigation map, domain model) | Done |
| Sample data and generated images | Done |
| Explorations (S25 directions A, B, C) | Done |
| Prototype (index.html with 4 flows, live swipe-demo.html) | Done |
| QA (screenshots, a11y report, lint report, traceability, review report, flow tests) | Done |
"""
open(os.path.join(ROOT, 'design', '05-qa', 'coverage.md'), 'w').write(out)
print(len(rows), 'screens', total, 'frames')
